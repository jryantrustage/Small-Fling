def auto_rescan_mismatched_files_with_steering_guide(
    verify_result: Dict[str, Any],
    project_id: Optional[str] = None,
    max_files_per_pass: int = 2,
    max_lines_per_file: int = 12,
) -> Dict[str, Any]:
    """
    Uses the instance-data `ocr_steering_guide` and frame-to-OCR correlation to perform targeted
    row-slice re-scans on closed `CODESCAN_FILE_START`..`CODESCAN_FILE_END` blocks whose `size`, `lines`,
    or `chars` attributes do not match the OCR output.
    """
    guide = verify_result.get("ocr_steering_guide") or {}
    targets = guide.get("rescan_targets") or []
    if not targets or not hasattr(state, "document_lines") or not state.document_lines:
        return {"rescanned_files": 0, "rescanned_lines": 0, "repairs": []}

    healed_tracker: set = state.orchestration_state.setdefault("_steering_rescanned_file_spans", set())
    repairs: List[Dict[str, Any]] = []
    files_done = 0
    lines_done = 0

    for tgt in targets:
        if files_done >= max_files_per_pass:
            break
        span_range = tgt.get("md_line_range") or [0, 0]
        start_ln, end_ln = int(span_range[0] or 0), int(span_range[1] or 0)
        if start_ln <= 0 or end_ln <= start_ln:
            continue
        span_key = (project_id or "active", start_ln, end_ln)
        if span_key in healed_tracker:
            continue
        healed_tracker.add(span_key)

        # Find candidate lines inside [start_ln, end_ln] that have low confidence, wrap flags, or tag boundaries
        cand_lns: List[int] = []
        for ln in range(start_ln, end_ln + 1):
            entry = state.document_lines.get(ln)
            meta = getattr(entry, "meta", {}) if (entry and hasattr(entry, "meta")) else (entry if isinstance(entry, dict) else {})
            conf = float(meta.get("confidence", 1.0) or 1.0)
            if ln in (start_ln, start_ln + 1, end_ln - 1, end_ln) or conf < 0.96 or meta.get("shift_detected"):
                cand_lns.append(ln)
        if not cand_lns:
            cand_lns = [start_ln, min(end_ln, start_ln + 1), max(start_ln, end_ln - 1), end_ln]
        cand_lns = sorted(set(cand_lns))[:max_lines_per_file]

        file_repairs = 0
        for ln in cand_lns:
            entry = state.document_lines.get(ln)
            old_txt = str(entry.get("text", "") if isinstance(entry, dict) else (entry or ""))
            meta = getattr(entry, "meta", {}) if (entry and hasattr(entry, "meta")) else (entry if isinstance(entry, dict) else {})
            fid = str(meta.get("frame_id") or "")
            img_path = find_frame_for_line(ln, frame_id=fid)
            if not img_path or not img_path.exists():
                continue
            finfo = state.captured_frames.get(fid) or {}
            line_item = {
                "line_number": ln,
                "gutter_number": ln,
                "text": old_txt,
                "bbox": (finfo.get("bounding_boxes", {}).get("line_boxes", {}) or {}).get(ln),
                "gutter_bbox": (finfo.get("bounding_boxes", {}).get("gutter_boxes", {}) or {}).get(ln),
            }
            try:
                cropped_txt, blank_locked, _ = _re_ocr_strip_with_upscale(
                    image_path=img_path,
                    line_item=line_item,
                    ln=ln,
                    ref_txt=old_txt,
                )
                new_txt = "" if blank_locked else _normalize_codescan_tags(cropped_txt.rstrip("\r\n"))
                if new_txt and new_txt != old_txt:
                    new_meta = dict(meta)
                    new_meta.update({
                        "line_number": ln,
                        "gutter_number": ln,
                        "status": "verified",
                        "confidence": 0.99,
                        "rescanned_by_steering_guide": True,
                        "frame_id": fid or img_path.stem,
                        "updated_at": datetime.now().isoformat(),
                    })
                    state.document_lines[ln] = state.MasterLine(new_txt, **new_meta)
                    file_repairs += 1
                    lines_done += 1
                    repairs.append({
                        "file_path": tgt.get("path"),
                        "line_number": ln,
                        "frame_id": fid or img_path.stem,
                        "before": old_txt[:80],
                        "after": new_txt[:80],
                    })
            except Exception:
                pass
        files_done += 1

    if lines_done > 0:
        try:
            state.save_persisted_state()
        except Exception:
            pass
    return {
        "rescanned_files": files_done,
        "rescanned_lines": lines_done,
        "repairs": repairs,
    }


