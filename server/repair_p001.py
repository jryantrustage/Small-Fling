import asyncio
import json
from pathlib import Path
from services.ocr_service import scan_image_with_minicpm

async def repair():
    p001_img = Path("storage/frames/raw_capture_p001_20261009_050315_047.png")
    if not p001_img.exists():
        print("p001_img does not exist!")
        return

    print("Running MiniCPM-V on p001 with expected_top=1...")
    res = await scan_image_with_minicpm(p001_img, expected_top=1)
    lines = res.get("lines", [])
    print(f"Extracted {len(lines)} lines from p001:")
    for l in lines[:5]:
        print(f"  Ln {l['line_number']}: {repr(l['text'])}")

    # Load current document state
    doc_state_file = Path("storage/data/document_state.json")
    with open(doc_state_file, "r", encoding="utf-8") as f:
        data = json.load(f)

    frames = data.get("frames", {})
    doc_lines = data.get("lines", {})

    # Find the frame for p001 (was frame_00050_00073...)
    p1_fid = None
    for fid, f in list(frames.items()):
        if f.get("page_index") == 1:
            p1_fid = fid
            break

    new_fid = "frame_00001_00024_20261009_050319_344"
    if p1_fid:
        old_frame = frames.pop(p1_fid)
        old_frame["frame_id"] = new_fid
        old_frame["filename"] = f"{new_fid}.png"
        old_frame["top_line"] = 1
        old_frame["bottom_line"] = 24
        old_frame["ocr_top_line"] = 1
        old_frame["ocr_bottom_line"] = max((l["line_number"] for l in lines), default=24)
        old_frame["extracted_line_count"] = len(lines)
        old_frame["ocr_extracted_count"] = len(lines)
        frames[new_fid] = old_frame

    # Remove the falsely shifted lines (53..73) that had Matrix_main headers
    for k in list(doc_lines.keys()):
        val = doc_lines[k]
        txt = val.get("text", "") if isinstance(val, dict) else str(val)
        if "Matrix_main" in txt or "Generated by Analyser" in txt or "Directory Structure" in txt:
            print(f"Removing falsely shifted line {k}: {repr(txt)}")
            doc_lines.pop(k, None)

    # Insert verbatim lines 1..24
    for item in lines:
        ln = item.get("line_number")
        if ln and ln <= 24:
            doc_lines[str(ln)] = {
                "line_number": ln,
                "gutter_number": ln,
                "text": item.get("text", ""),
                "is_blank": not bool(item.get("text", "").strip()),
                "is_wrapped": item.get("is_wrapped", False),
                "wrapped_line_count": item.get("wrapped_line_count", 1),
                "status": "verified",
                "confidence": 0.98,
                "frame_id": new_fid,
                "notes": "MiniCPM-V OCR (verbatim Page 1)",
                "updated_at": "2026-10-09T05:03:19.346838"
            }

    data["frames"] = frames
    data["lines"] = doc_lines

    with open(doc_state_file, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)

    print(f"Successfully repaired document_state.json! Total lines: {len(doc_lines)}, Total frames: {len(frames)}")

if __name__ == "__main__":
    asyncio.run(repair())
