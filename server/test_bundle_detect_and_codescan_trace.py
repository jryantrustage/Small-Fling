def _render_dark_mode_editor_png(lines_with_gutter: List[tuple], title_file_name: str = "") -> bytes:
    """Renders a realistic 1920x1080 Dark-Mode Markdown editor screenshot for OCR + capture marker testing."""
    img = np.full((1080, 1920, 3), (24, 26, 30), dtype=np.uint8)
    if title_file_name:
        cv2.rectangle(img, (0, 0), (1920, 64), (12, 14, 18), -1)
        cv2.putText(
            img,
            title_file_name,
            (110, 42),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.82,
            (242, 245, 250),
            2,
            cv2.LINE_AA,
        )
    y = 340
    for gutter_num, code_text in lines_with_gutter:
        if gutter_num is not None:
            cv2.putText(
                img,
                str(gutter_num),
                (62, y),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.62,
                (170, 180, 195),
                2,
                cv2.LINE_AA,
            )
        if code_text:
            cv2.putText(
                img,
                code_text,
                (116, y),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.62,
                (238, 242, 248),
                2,
                cv2.LINE_AA,
            )
        y += 27
    ok, enc = cv2.imencode(".png", img)
    assert ok
    return enc.tobytes()


